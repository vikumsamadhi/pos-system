export type TranslationKey = keyof typeof TRANSLATIONS

interface I18nContextType {
  language: Language
  setLanguage: (lang: Language) => void
  t: (key: TranslationKey) => string
  productTitle: (p: { name: string; nameSi?: string | null }) => { main: string; secondary?: string }
}

const I18nContext = createContext<I18nContextType | null>(null)

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLangState] = useState<Language>(() => {
    const saved = localStorage.getItem('pos_language')
    return saved === 'si' ? 'si' : 'en'
  })

  function setLanguage(lang: Language) {
    setLangState(lang)
    localStorage.setItem('pos_language', lang)
  }

  function t(key: TranslationKey): string {
    const entry = TRANSLATIONS[key]
    if (!entry) return key
    return entry[language] || entry.en || key
  }

  function productTitle(p: { name: string; nameSi?: string | null }): { main: string; secondary?: string } {
    if (language === 'si') {
      if (p.nameSi && p.nameSi.trim().length > 0) {
        return { main: p.nameSi, secondary: p.name }
      }
      return { main: p.name }
    } else {
      if (p.name && p.name.trim().length > 0) {
        return { main: p.name, secondary: p.nameSi || undefined }
      }
      return { main: p.nameSi || '' }
    }
  }

  return (
    <I18nContext.Provider value={{ language, setLanguage, t, productTitle }}>
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n(): I18nContextType {
  const ctx = useContext(I18nContext)
  if (!ctx) {
    throw new Error('useI18n must be used within I18nProvider')
  }
  return ctx
}
